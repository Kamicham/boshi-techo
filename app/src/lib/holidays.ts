/** 内閣府の表がある年（この外は祝日法で数える） */
export const CAO_YEARS = { from: 2020, to: 2027 } as const;

const pad = (n: number) => String(n).padStart(2, "0");
const ymd = (y: number, m: number, d: number) => `${y}-${pad(m)}-${pad(d)}`;

/** 曜日（0 = 日曜 … 6 = 土曜）。1970-01-01 は木曜 */
export function weekday(d: string): number {
  return (((toDay(d) + 4) % 7) + 7) % 7;
}

/** その月の第 n 月曜日 */
function nthMonday(y: number, m: number, n: number): number {
  const first = weekday(ymd(y, m, 1));
  return 1 + ((8 - first) % 7) + (n - 1) * 7;
}

/**
 * 春分日・秋分日の近似（1980〜2099年向けの、よく使われる式）。本当の日は、国立天文台が前の年の2月に官報（暦要項）で出す。
 * 内閣府の表の2020〜2027年とは、すべて合う（holidays.test.ts）
 */
export function equinoxDay(y: number, which: "春分" | "秋分"): number {
  const base = which === "春分" ? 20.8431 : 23.2488;
  return Math.floor(base + 0.242194 * (y - 1980) - Math.floor((y - 1980) / 4));
}

/** 国民の祝日に関する法律で数えた、その年の祝日と休日（日付 → 名前）。2028年から先（と2019年まで）に使う */
export function lawHolidays(y: number): Map<string, string> {
  // 第2条の「国民の祝日」
  const festive = new Map<string, string>([
    [ymd(y, 1, 1), "元日"],
    [ymd(y, 1, nthMonday(y, 1, 2)), "成人の日"],
    [ymd(y, 2, 11), "建国記念の日"],
    [ymd(y, 2, 23), "天皇誕生日"],
    [ymd(y, 3, equinoxDay(y, "春分")), "春分の日"],
    [ymd(y, 4, 29), "昭和の日"],
    [ymd(y, 5, 3), "憲法記念日"],
    [ymd(y, 5, 4), "みどりの日"],
    [ymd(y, 5, 5), "こどもの日"],
    [ymd(y, 7, nthMonday(y, 7, 3)), "海の日"],
    [ymd(y, 8, 11), "山の日"],
    [ymd(y, 9, nthMonday(y, 9, 3)), "敬老の日"],
    [ymd(y, 9, equinoxDay(y, "秋分")), "秋分の日"],
    [ymd(y, 10, nthMonday(y, 10, 2)), "スポーツの日"],
    [ymd(y, 11, 3), "文化の日"],
    [ymd(y, 11, 23), "勤労感謝の日"],
  ]);
  const out = new Map(festive);
  for (const d of festive.keys()) {
    // 第3条第2項: 祝日が日曜日に当たる時は、その後で最も近い「国民の祝日」でない日を休日にする（振替休日）
    if (weekday(d) === 0) {
      let x = addDays(d, 1);
      while (festive.has(x)) x = addDays(x, 1);
      out.set(x, "休日");
    }
    // 第3条第3項: 前の日と次の日が「国民の祝日」である日（祝日でない日）は休日（国民の休日。9月の敬老の日と秋分の日の間など）
    const next = addDays(d, 1);
    if (!festive.has(next) && festive.has(addDays(d, 2))) out.set(next, "休日");
  }
  return out;
}

const cache = new Map<number, Map<string, string>>();

/** その年の祝日と休日（日付 → 名前）。2020〜2027年は内閣府の表、ほかは祝日法で数える（春分・秋分は近似） */
export function holidaysOf(y: number): Map<string, string> {
  let m = cache.get(y);
  if (!m) {
    const table = CAO[y];
    m = table ? new Map(table.map((x) => [`${y}-${x.slice(0, 5)}`, x.slice(6)])) : lawHolidays(y);
    cache.set(y, m);
  }
  return m;
}

/** 祝日・休日の名前（土日・年末年始だけの日は無し） */
export function holidayName(d: string): string | undefined {
  return holidaysOf(Number(d.slice(0, 4))).get(d);
}

/** 役所の休みか（土日・国民の祝日と休日・12/29〜1/3） */
export function isOfficeHoliday(d: string): boolean {
  const w = weekday(d);
  if (w === 0 || w === 6) return true;
  const md = d.slice(5);
  if (md >= "12-29" || md <= "01-03") return true;
  return holidayName(d) !== undefined;
}

/** d が役所の休みなら、次の開庁日。休みでなければ d のまま（地方自治法第4条の2第4項・行政機関の休日に関する法律第2条） */
export function nextOpenDay(d: string): string {
  let x = d;
  while (isOfficeHoliday(x)) x = addDays(x, 1);
  return x;
}

/** d が役所の休みなら、前の開庁日。休みでなければ d のまま */
export function prevOpenDay(d: string): string {
  let x = d;
  while (isOfficeHoliday(x)) x = addDays(x, -1);
  return x;
}

/** 休みの理由（「日曜」「憲法記念日」「年末年始」）。休みでなければ無し。根拠の文や試験の報告に使う */
export function holidayWhy(d: string): string | undefined {
  const name = holidayName(d);
  if (name) return name === "休日" ? "休日（振替休日か国民の休日）" : name;
  const md = d.slice(5);
  if (md >= "12-29" || md <= "01-03") return "年末年始";
  const w = weekday(d);
  return w === 0 ? "日曜" : w === 6 ? "土曜" : undefined;
}

