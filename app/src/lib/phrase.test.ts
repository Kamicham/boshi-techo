// 短い1行を文節に近いまとまりに分ける（lib/phrase.ts・デモの会話が見つけた⑧・2026-11-06）。
// デモで見つかった折れ方（「ひなた／へ」「見てい／た」「ママ（美咲）／からの」「数え直し／ました」「日々」だけの行）が、
// まとまりの中に入って起きない事と、まとまりの間にだけ折れる所がある事を見る
import { describe, expect, it } from "vitest";
import { PHRASE_MAX, phraseChunks } from "./phrase";

const NB = "\u00A0";
const chunks = (s: string) => phraseChunks(s);

describe("文節に近いまとまりに分ける", () => {
  it("デモで見つかった折れ方は、まとまりの中に入る", () => {
    // 映画の手紙の場面・みんなの章の手紙の行（「ひなた／へ」）
    expect(chunks("ママ（美咲）から ひなたへ")).toEqual(["ママ（美咲）から", " ", "ひなたへ"]);
    // 映画の写真の一言（「見てい／た」）
    expect(chunks("線が2本。しばらく二人で黙って見ていた")).toEqual(["線が", "2本。", "しばらく", "二人で", "黙って", "見ていた"]);
    // 1歳の誕生日の札（「ママ（美咲）／からの」）
    expect(chunks("💌 ママ（美咲）からの手紙が開きました")).toEqual([`💌${NB}ママ（美咲）からの`, "手紙が", "開きました"]);
    // 気づきの札（「数え直し／ました」）
    expect(chunks("美咲の育休の始まりを6月22日に数え直しました")).toEqual(["美咲の", "育休の", "始まりを", "6月22日に", "数え直しました"]);
    // 映画の最初の画面の題（「日々」だけの行）
    expect(chunks("ひなたへ　1歳までの日々")).toEqual(["ひなたへ", "　", "1歳までの", "日々"]);
  });

  it("今日の画面の行（名前と「の番」・届けの束・生まれた日の札）", () => {
    expect(chunks("翔太の番 2件")).toEqual(["翔太の", "番", " ", "2件"]);
    expect(chunks("生まれた届け4件は、翔太の番です")).toEqual(["生まれた", "届け", "4件は、", "翔太の", "番です"]);
    expect(chunks("おなかにいた頃に書いた手紙が1通、1歳の誕生日を待っています。")).toEqual([
      "おなかにいた",
      "頃に",
      "書いた",
      "手紙が",
      "1通、",
      "1歳の",
      "誕生日を",
      "待っています。",
    ]);
    expect(chunks("届けは下の1枚に。あなたは、休む事を一番に。")).toEqual(["届けは", "下の", "1枚に。", "あなたは、", "休む事を", "一番に。"]);
    expect(chunks("産婦健診（産後2週間）を受ける")).toEqual(["産婦健診（産後2週間）を", "受ける"]);
  });

  it("絵文字は後ろの語とつなぐ（「🎙」だけが行の終わりに残らない）・「お」「ご」は後ろの語につける", () => {
    expect(chunks("📷 はじめましての写真・🎙 声を残す")).toEqual([`📷${NB}はじめましての`, "写真・", `🎙${NB}声を`, "残す"]);
    expect(chunks("・🎙 声つき")).toEqual(["・", `🎙${NB}声つき`]);
    expect(chunks("鹿児島から箱が届いた。手編みの帽子とお守り")).toEqual(["鹿児島から", "箱が", "届いた。", "手編みの", "帽子と", "お守り"]);
    expect(chunks("うれしいお知らせです")).toEqual(["うれしい", "お知らせです"]);
    expect(chunks("写真・お守り")).toEqual(["写真・", "お守り"]);
  });

  it("漢字の間の送り仮名1字はつなぎ（複合の語）、助詞1字の所では分ける", () => {
    expect(chunks("思い出を書き込む")).toEqual(["思い出を", "書き込む"]);
    expect(chunks("申し込みの手続き")).toEqual(["申し込みの", "手続き"]);
    expect(chunks("手紙が開きました")).toEqual(["手紙が", "開きました"]);
    expect(chunks("体を休める")).toEqual(["体を", "休める"]);
  });

  it("かぎ括弧の中の文は、中でも分ける（丸括弧の中だけ分けない）", () => {
    expect(chunks("「うれしいお知らせです。4月26日に、ひなたが生まれました。」")).toEqual([
      "「うれしい",
      "お知らせです。",
      "4月26日に、",
      "ひなたが",
      "生まれました。」",
    ]);
  });

  it("字を足し引きしない（つないだ空白だけ、改行しない空白に替わる）", () => {
    for (const s of ["ママ（美咲）から ひなたへ", "📷 はじめましての写真・🎙 声を残す", "（閉じない括弧の中は、ずっと1つ", "  前と後ろの空白  ", "", "English text stays", "转成文字在手册内部完成"]) {
      expect(chunks(s).join("").replaceAll(NB, " ")).toBe(s);
    }
  });

  it("中文・English は、空白の所でだけ分かれる（日本語でない文は Phrase が分けない）", () => {
    expect(chunks("Read Year One as a book")).toEqual(["Read", " ", "Year", " ", "One", " ", "as", " ", "a", " ", "book"]);
    expect(chunks("在一本书里读第一年")).toEqual(["在一本书里读第一年"]);
  });

  it("まとまりは、見本の家族のどの行でも PHRASE_MAX 字まで（長い丸括弧の中だけ、それより長くなる）", () => {
    const lines = [
      "ママ（美咲）からの手紙が開きました",
      "美咲の育休の始まりを6月22日に数え直しました",
      "おなかにいた頃に書いた手紙が1通、1歳の誕生日を待っています。",
      "職場に生まれた事を伝える",
      "一時金の差額を申請する",
    ];
    expect(lines.flatMap(chunks).filter((c) => [...c].length > PHRASE_MAX)).toEqual([]);
  });
});
