/** 曲線の最後の月齢（これより先は帯を描かない） */
export const GROWTH_MAX_MONTH = 27;

/** 1か月の平均の日数（月齢を日数から出す時の近似） */
const DAYS_PER_MONTH = 30.4375;

/** 生後日数 → 月齢（小数。描くためだけの近似） */
export function monthsFromDays(days: number): number {
  return days / DAYS_PER_MONTH;
}

/**
 * ある月齢の、各パーセンタイルの値（表の点の間は直線で近似）。表の範囲の外は null（作り話で延ばさない）。
 * 返す並びは PERCENTILES と同じ。
 */
export function bandAt(measure: GrowthMeasure, sex: GrowthSex, month: number): number[] | null {
  const rows = GROWTH_TABLE[measure];
  if (month < rows[0].m || month > rows[rows.length - 1].m) return null;
  for (let i = 0; i < rows.length - 1; i++) {
    const a = rows[i];
    const b = rows[i + 1];
    if (month >= a.m && month <= b.m) {
      const t = b.m === a.m ? 0 : (month - a.m) / (b.m - a.m);
      return a[sex].map((v, k) => v + (b[sex][k] - v) * t);
    }
  }
  return null;
}

/** 記録の1点（月齢と値。値は家族が話したか紙から写した物だけ） */
export interface GrowthPoint {
  month: number;
  value: number;
  date: string;
}
