// 今やる事が無い日の1枚（Techo の Calm）の見出しと、一言の頭。試験から読めるよう、JSX の無いこのファイルに置く。
// 手帳が気づいた事（引っ越した後の転入の届けの期限など）が同じ画面に出ている日は、「急ぐ事はありません」「何もしなくて大丈夫」と言わない。
// 言えるのは予定表の事だけなので、予定表の急ぎが無い事と、気づいた事を先に見てほしい事を言う（統括の足し 3・UX の見直し C10⑤ の画面の分・2026-11-05）。
// 画面の言葉で返す（辞書は lib/i18n/dict/today.ts。サーバと試験ではいつも日本語）
import { t } from "@/lib/i18n";

/** advisor: 手帳が気づいた事の箱が、この1枚の上（above）か下（below）に出ている時。無い時は undefined */
export type CalmInput = { before: number; others: number; advisor?: "above" | "below" };

export function calmWords({ before, others, advisor }: CalmInput): { title: string; lead: string } {
  if (advisor) {
    return {
      // 上に「手帳を始める前の事」がある時・家族のほかの人の番の事がある時は、今までどおり言う範囲を狭める
      title: before > 0 ? t("ほかに、予定表の急ぎはありません") : others > 0 ? t("あなたの予定表に、今週の急ぎはありません") : t("予定表の急ぎはありません"),
      lead: advisor === "above" ? t("上の、手帳が気づいた事を先に見てください。") : t("下の、手帳が気づいた事を先に見てください。"),
    };
  }
  // 家族のほかの人の番で、期限のある事が「このあと」に残っている時は、家族全体が大丈夫とは言わない（なりきり sim-15・sim-14）
  // 上に「手帳を始める前の事」（聞く事・まだの事）がある時も、何もしなくて大丈夫とは言わない（2026-11-04）
  // UX 2026-11-04: 上の箱を受ける言い回し（「上の…のほかは」）は一度で読めなかったので、それだけで読める見出しに
  return {
    title: before > 0 ? t("ほかに、今すぐやる事はありません") : others > 0 ? t("あなたは今週、急ぐ事はありません") : t("今週は、何もしなくて大丈夫"),
    lead: others > 0 ? t("家族の番の事は、下の「このあと」に日付の順で並べています。") : "",
  };
}
